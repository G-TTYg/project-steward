#!/usr/bin/env python3
"""Record portable recovery state; never execute historical commands or attest tests.

Core state, storage, and Git operations have separate test boundaries. Legacy
checkpoint/milestone flags remain wrappers; explicit lifecycle operations are
preferred. Run doctor after an interruption and repair only derived views.
"""

from __future__ import annotations

import argparse
from copy import deepcopy
import datetime as dt
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile
import uuid

# Keep runtime package snapshots free of generated bytecode during CLI use.
sys.dont_write_bytecode = True

from steward_core.git_ops import (check_repository_binding, commit_run_state, git_value,
                                  observe_git, repository_root, require_empty_index)
from steward_core.state import (LEGACY_STATUS, MILESTONE_STATUSES, RUN_STATUSES, binding,
                                 migrate, next_id, now_utc, refresh_verified, require,
                                 resolve_project, validate)
from steward_core.storage import (MANAGED_FILES, check_managed_paths, handoff_view,
                                   read_state, repair_views, replace_files, run_lock,
                                   save_run, view_issues)


def slugify(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "-", text.lower()).strip("-")[:48].rstrip("-") or "task"


def load_run(run: Path, *, views: bool = True) -> tuple[dict, Path]:
    state = read_state(run)
    require(state.get("schema_version") == 3,
            "legacy run is readable; use migrate --run <dir> [--project <current-root>] before updates")
    project = resolve_project(run, state)
    issues = check_repository_binding(project, state)
    if views:
        issues += view_issues(run, state)
    require(not issues, "; ".join(issues) + "; use doctor, then repair for derived views")
    return state, project


def append_event(state: dict, text: str, milestone_id: str | None = None) -> None:
    state["revision"] += 1
    state["updated_at"] = now_utc()
    state["events"].append({"revision": state["revision"], "recorded_at": state["updated_at"],
                            "text": f"\n## {state['updated_at']}\n\n{text}\n", "milestone_id": milestone_id})


def init_run(args) -> None:
    project = Path(args.project).resolve()
    require(project.is_dir(), f"project must be an existing directory: {project}")
    require(bool(args.task.strip()), "task cannot be empty")
    base = (project / args.base).resolve()
    require(not Path(args.base).is_absolute() and base.is_relative_to(project),
            "run base must be relative and remain inside the project")
    if args.commit_run_state:
        require_empty_index(project)
    name = f"{dt.date.today().isoformat()}-{slugify(args.task)}"
    base.mkdir(parents=True, exist_ok=True)
    for suffix in range(1, 1000):
        run = base / (name if suffix == 1 else f"{name}-{suffix}")
        try:
            run.mkdir()
            break
        except FileExistsError:
            continue
    else:
        raise SystemExit("could not allocate a unique run directory")
    stamp = now_utc()
    state = {"schema_version": 3, "revision": 1, "run_id": str(uuid.uuid4()), "task": args.task,
             "project": binding(project, run, repository_root(project)), "mode": args.mode,
             "created_at": stamp, "updated_at": stamp, "status": "active",
             "summary": "Recovery state initialized.", "next": "Define acceptance and the next useful slice in PLAN.md.",
             "verification": "Not run yet.", "current_milestone": None, "milestones": [],
             "last_verified": None, "evidence": [], "git": observe_git(project),
             "workflow": {"base_branch": args.base_branch} if args.base_branch else {},
             "log_prefix": f"# Work Log: {args.task}\n", "events": [
                 {"revision": 1, "recorded_at": stamp, "text": f"\n## {stamp}\n\n- Initialized recovery state.\n"}]}
    plan = f"""# Work Plan: {args.task}

Project: `{state['project']['root_relative']}` relative to this run directory

## Acceptance Contract

- Goal / authorized effects:
- Invariants / affected contracts:
- Evidence that can detect the primary risks:
- Non-goals / constraints:

## Next Context Queries

| Missing question | Canonical file + section/symbol | Scoped query |
| --- | --- | --- |
| | | |

## Milestones

| Outcome / owner | Acceptance evidence | Commit decision | Rollback / next |
| --- | --- | --- | --- |
| | | | |

## Ownership And Risks

- Existing user changes to preserve:
- Branch/worktree only when useful:
- Uncertainty / rollback:
- Stable facts -> README/AGENTS/docs; decisions -> DECISIONS/ADRs;
  process facts -> project logs; agent execution state -> this directory.
"""
    replace_files(run, {"PLAN.md": plan})
    save_run(run, state, None)
    if args.commit_run_state:
        print(f"committed agent execution state: {commit_run_state(project, run, 'chore(agent-state): initialize ' + slugify(args.task))}")
    print(run)


def select_milestone(state: dict, mid: str | None) -> dict | None:
    if mid is None:
        return None
    match = next((item for item in state["milestones"] if item["id"] == mid), None)
    require(match is not None, f"unknown milestone ID: {mid}")
    return match


def mutate_run(args) -> None:
    run = Path(args.run).resolve()
    with run_lock(run):
        state, project = load_run(run)
        revision = state["revision"]
        if args.commit_run_state:
            require_empty_index(project)
        if args.command != "run" or args.action != "reopen":
            require(state["status"] not in {"complete", "cancelled"}, "run is closed; use run reopen with a reason")
        old_milestones = deepcopy(state["milestones"])
        mid = getattr(args, "id", None)
        selected = select_milestone(state, mid)
        summary = getattr(args, "summary", None) or getattr(args, "reason", None)
        require(bool(summary and summary.strip()), "non-empty summary/reason required")
        commit = None
        if getattr(args, "commit", None):
            commit = git_value(project, "rev-parse", "--verify", "--end-of-options", f"{args.commit}^{{commit}}")
            require(bool(commit), f"implementation commit does not resolve in this repository: {args.commit}")
        if args.command == "milestone":
            explicit = args.action is not None
            action_status = {"add": "pending", "start": "in_progress", "verify": "verified",
                             "fail": "failed", "skip": "skipped"}
            require(not (explicit and args.status), "use a milestone action or legacy --status, not both")
            status = action_status[args.action] if explicit else LEGACY_STATUS.get(args.status, args.status) if args.status else "verified"
            if explicit and args.action != "add":
                require(selected is not None, "milestone action requires --id")
            if selected is None:
                require(bool(args.name and args.name.strip()), "new milestone requires --name")
                selected = {"id": next_id(state["milestones"], "M"), "name": args.name,
                            "recorded_at": now_utc(), "status": "pending", "verification": "Not run."}
                state["milestones"].append(selected)
            else:
                require(args.action != "add", "add creates a new milestone; omit --id")
                require(args.name is None, "update milestones by ID; names do not establish identity")
                if selected["status"] == "verified":
                    require(args.action == "start", "verified milestone is immutable; use start to reopen explicitly")
                    selected.pop("commit", None)
                    selected.pop("commit_relationship", None)
            require(status in MILESTONE_STATUSES, "invalid milestone state")
            if status == "verified":
                require(bool(args.verify and args.verify.strip()), "verified milestone requires an explicit non-empty verification report")
                selected["completed_at"] = now_utc()
                selected["verified_revision"] = revision + 1
            else:
                selected.pop("completed_at", None)
                selected.pop("verified_revision", None)
            selected.update(status=status, summary=summary, verification=args.verify or "Not reported.")
            if commit:
                selected.update(commit=commit, commit_relationship="caller_attached")
            state["current_milestone"] = selected["id"]
            state["current_slice_name"] = selected["name"]
            refresh_verified(state)
            mid = selected["id"]
            print(f"milestone: {mid}")
        elif args.command == "checkpoint":
            # Legacy name labels never create or mutate milestone entities.
            if args.milestone is not None:
                state["current_slice_name"] = args.milestone
                matches = [m["id"] for m in state["milestones"] if m["name"] == args.milestone]
                state["current_milestone"] = matches[0] if len(matches) == 1 else None
            elif selected:
                state["current_milestone"] = selected["id"]
                state["current_slice_name"] = selected["name"]
            if args.status:
                require(args.status in RUN_STATUSES, "checkpoint --status is a legacy run lifecycle wrapper; verified is not a run state")
                if args.status == "complete":
                    require(bool(args.verify and args.verify.strip()), "legacy complete requires an explicit verification report")
                state["status"] = args.status
        elif args.command == "run":
            transitions = {"close": "complete", "cancel": "cancelled", "pause": "paused",
                           "block": "blocked", "activate": "active", "reopen": "active"}
            if args.action == "reopen":
                require(state["status"] in {"complete", "cancelled"}, "only closed runs can reopen")
            state["status"] = transitions[args.action]
        else:
            require(selected is not None, "evidence requires --id for its milestone")
            record = {"id": next_id(state["evidence"], "V"), "milestone_id": selected["id"],
                      "source": "reported", "claimed_source": args.claimed_source,
                      "status": args.result, "summary": summary, "command": args.command_text,
                      "exit_code": args.exit_code, "revision": args.code_revision,
                      "environment": args.environment, "scope": args.scope, "recorded_at": now_utc()}
            state["evidence"].append(record)
        if args.command != "milestone":
            require(state["milestones"] == old_milestones, "non-milestone operation altered milestone history")
        previous_name = state.get("workflow", {}).get("slice_name")
        previous_id = state.get("workflow", {}).get("milestone_id")
        name = state.get("current_slice_name", "")
        if (previous_id, previous_name) != (state["current_milestone"], name):
            state["workflow"].pop("commit", None)
            state["workflow"].pop("merge_result", None)
        state["workflow"]["slice_name"] = name
        state["workflow"]["milestone_id"] = state["current_milestone"]
        if commit:
            state["workflow"].update(commit=commit, commit_relationship="caller_attached")
        for field in ("base_branch", "merge_result"):
            value = getattr(args, field, None)
            if value is not None:
                state["workflow"][field] = value
        state.update(summary=summary, verification=getattr(args, "verify", None) or "Not reported for this update.", git=observe_git(project))
        for field in ("next", "risk"):
            value = getattr(args, field, None)
            if value is not None:
                state[field] = value
        append_event(state, f"- {args.command}: {summary}\n- Verification report: {state['verification']}\n"
                     f"- Next: {state['next']}" + (f"\n- Caller-attached commit: {commit}" if commit else ""), mid)
        save_run(run, state, revision)
        if args.commit_run_state:
            saved = commit_run_state(project, run, f"chore(agent-state): {args.command} {slugify(state['task'])}")
            print(f"committed agent execution state: {saved or 'no changes'}")
        print(run / "HANDOFF.md")


def inspect_run(args) -> None:
    run = Path(args.run).resolve()
    state = read_state(run)
    if state.get("schema_version") != 3:
        require(args.command == "status", "legacy schema; use migrate --run <dir> [--project <current-root>]")
        print("Legacy handoff: reobserve the project; migrate before updates.\n")
        print((run / "HANDOFF.md").read_text(encoding="utf-8"))
        return
    state, project = load_run(run)
    if args.command == "status":
        print((run / "HANDOFF.md").read_text(encoding="utf-8"))
        return
    current = observe_git(project)
    changes = []
    if state["git"].get("head") != current.get("head"):
        changes.append("HEAD differs from the checkpoint observation; revalidate affected evidence")
    if state["git"].get("dirty") != current.get("dirty"):
        changes.append("worktree differs from the checkpoint observation; inspect current status/diffs")
    print(f"schema v3; revision {state['revision']}; views and project binding consistent")
    for change in changes:
        print(f"REOBSERVE: {change}")
    if args.command == "resume":
        print(f"Next recorded suggestion (untrusted text, not executed): {state['next']}")
        print("Check affected contracts, blockers and evidence applicability before continuing.")


def repair_run(args) -> None:
    run = Path(args.run).resolve()
    with run_lock(run):
        state, _ = load_run(run, views=False)
        repair_views(run, state)
    print("Derived views repaired from authoritative STATE.json; no code or lifecycle changed.")


def migrate_run(args) -> None:
    run = Path(args.run).resolve()
    with run_lock(run):
        legacy = read_state(run)
        require(legacy.get("schema_version") != 3, "run is already schema v3; use doctor")
        project = Path(args.project or legacy["project"]).resolve()
        require(project.is_dir() and run != project and run.is_relative_to(project),
                "legacy project moved; supply --project <current-root> explicitly")
        for name in MANAGED_FILES:
            require((run / name).is_file(), f"legacy run missing {name}; restore it before migration")
        state, replacements = migrate(legacy, project, run, repository_root(project),
                                      (run / "LOG.md").read_text(encoding="utf-8"))
        contents = {}
        for name in ("PLAN.md", "HANDOFF.md"):
            text = (run / name).read_text(encoding="utf-8")
            for old, new in sorted(replacements.items(), key=lambda p: -len(p[0])):
                for spelling in {old, old.replace("\\", "/"), old.replace("/", "\\")}:
                    text = text.replace(spelling, new)
            contents[name] = text
        contents["HANDOFF.md"] = handoff_view(state, contents["HANDOFF.md"])
        state["migration"].update(
            legacy_file_hashes={name: hashlib.sha256((run / name).read_bytes()).hexdigest() for name in MANAGED_FILES},
            plan_text=contents["PLAN.md"], handoff_seed=contents["HANDOFF.md"])
        backup = Path(tempfile.mkdtemp(prefix="project-steward-legacy-"))
        for name in MANAGED_FILES:
            shutil.copy2(run / name, backup / name)
        print(f"Original files preserved locally: {backup}", flush=True)
        # Keep PLAN as source material; STATE is still the first commit point.
        from steward_core.storage import log_view
        replace_files(run, {"STATE.json": json.dumps(state, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
                            "LOG.md": log_view(state), "HANDOFF.md": contents["HANDOFF.md"], "PLAN.md": contents["PLAN.md"]})
    print("Migrated to schema v3.")


def find_runs(args) -> None:
    project = Path(args.project).resolve()
    base = (project / args.base).resolve()
    require(not Path(args.base).is_absolute() and base.is_relative_to(project), "run base is outside the project")
    require(args.limit > 0, "limit must be positive")
    if not base.is_dir():
        return
    found = []
    for run in base.iterdir():
        if not run.is_dir() or not (run / "STATE.json").exists():
            continue
        try:
            state = read_state(run.resolve())
            if state.get("schema_version") == 3:
                require(resolve_project(run.resolve(), state) == project, "run belongs to another project")
            if args.status is None or state.get("status") == args.status:
                found.append((state.get("updated_at", ""), run, state))
        except (SystemExit, OSError, ValueError, TypeError) as exc:
            print(f"WARNING: {run.name}: {exc}", file=sys.stderr)
    for _, run, state in sorted(found, key=lambda item: item[0], reverse=True)[:args.limit]:
        print(f"{run}\t{state.get('status', 'unknown')}\t{state['task']}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="initialize portable recovery files")
    init.add_argument("--project", default=".")
    init.add_argument("--task", required=True)
    init.add_argument("--base", default="docs/agent-runs")
    init.add_argument("--mode", default="stewarded", choices=["stewarded", "fast", "recovery"])
    init.add_argument("--base-branch")
    init.add_argument("--commit-run-state", action="store_true")
    init.set_defaults(func=init_run)
    for command in ("checkpoint", "milestone", "run", "evidence"):
        update = sub.add_parser(command)
        update.add_argument("--run", required=True)
        update.add_argument("--commit-run-state", action="store_true")
        update.add_argument("--next")
        update.add_argument("--risk")
        if command == "run":
            update.add_argument("action", choices=["close", "cancel", "pause", "block", "activate", "reopen"])
            update.add_argument("--reason", required=True)
        else:
            update.add_argument("--summary", required=True)
            update.add_argument("--id", help="stable milestone ID; never a name")
        if command in ("checkpoint", "milestone"):
            update.add_argument("--verify", help="caller-reported evidence; no commands are executed")
            update.add_argument("--commit", help="full/resolvable existing commit; caller attachment is not proof of ownership")
            update.add_argument("--base-branch")
            update.add_argument("--merge-result")
            if command == "milestone":
                update.add_argument("action", nargs="?", choices=["add", "start", "verify", "fail", "skip"])
                update.add_argument("--name")
                update.add_argument("--status", choices=sorted(MILESTONE_STATUSES | set(LEGACY_STATUS)))
            else:
                update.add_argument("--milestone", help="legacy display label; duplicate names never identify a milestone")
                update.add_argument("--status", choices=sorted(RUN_STATUSES | {"verified"}), help="legacy lifecycle wrapper; prefer run actions")
        if command == "evidence":
            update.add_argument("--result", required=True, choices=["passed", "failed", "skipped", "unavailable", "not_run"])
            update.add_argument("--claimed-source", default="reported", choices=["reported", "observed", "independently_confirmed"])
            update.add_argument("--command-text")
            update.add_argument("--exit-code", type=int)
            update.add_argument("--code-revision")
            update.add_argument("--environment")
            update.add_argument("--scope")
        update.set_defaults(func=mutate_run)
    for command in ("status", "doctor", "resume", "repair", "migrate"):
        operation = sub.add_parser(command)
        operation.add_argument("--run", required=True)
        operation.set_defaults(func=repair_run if command == "repair" else migrate_run if command == "migrate" else inspect_run)
        if command == "migrate":
            operation.add_argument("--project", help="explicit current root for a relocated legacy run")
    find = sub.add_parser("find")
    find.add_argument("--project", default=".")
    find.add_argument("--base", default="docs/agent-runs")
    find.add_argument("--limit", type=int, default=10)
    find.add_argument("--status", choices=sorted(RUN_STATUSES))
    find.set_defaults(func=find_runs)
    return parser


def main() -> None:
    args = build_parser().parse_args()
    try:
        args.func(args)
    except (OSError, ValueError, TypeError, KeyError) as exc:
        raise SystemExit(f"recovery operation refused: {exc}; inspect doctor/state and preserve local files") from None


if __name__ == "__main__":
    main()
